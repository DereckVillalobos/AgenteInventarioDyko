function buildLots(sku: string, today: string, spec: Spec): Lot[] {
  return spec.lots.map((lot, i) => ({
    id: `${sku}-L${i + 1}`,
    qty: lot.qty,
    expiry: addDaysIso(today, lot.days),
  }));
}

export function buildCatalog(now = new Date()): Product[] {
  const today = todayLocalIso(now);
  return SPECS.map((spec, index) => {
    const lots = buildLots(spec.sku, today, spec);
    const stockFromLots = lots.reduce((s, l) => s + l.qty, 0);
    const stock = spec.perishable || lots.length ? stockFromLots : spec.stock;
    return {
      id: `p${String(index + 1).padStart(2, "0")}`,
      sku: spec.sku,
      name: spec.name,
      brand: spec.brand,
      category: spec.category,
      unit: spec.unit,
      cost: spec.cost,
      price: spec.price,
      stock,
      minStock: spec.minStock,
      maxStock: spec.maxStock,
      leadDays: spec.leadDays,
      perishable: spec.perishable,
      lots,
      dailySales: generateDailySales(90, today, spec.sales),
    };
  });
}
